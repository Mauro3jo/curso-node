import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { Router } from 'express';
import { mongoDatabase, serve } from '../test-support/mongo.js';
import { createModels } from '../ejercicios/04-rest/models.js';
import { createAuth } from '../ejercicios/04-rest/auth.js';
import { catalogRoutes } from '../ejercicios/04-rest/catalog.js';
import { createRestApp } from '../ejercicios/04-rest/app.js';

test('catálogo valida referencias, permisos, búsqueda literal y baja lógica', { timeout: 60000 }, async t => {
  const models = createModels(await mongoDatabase(t));
  await Promise.all(Object.values(models).map(m => m.init()));
  const user = await models.User.create({ nombre: 'Editor', correo: 'editor@example.test', password: 'hash-de-fixture' });
  const admin = await models.User.create({ nombre: 'Admin', correo: 'admin@example.test', password: 'hash-de-fixture', rol: 'ADMIN_ROLE' });
  const auth = createAuth(models, randomBytes(32).toString('hex'));
  const token = auth.issue(user), adminToken = auth.issue(admin);
  const request = await serve(t, createRestApp({ routes: Router().use(catalogRoutes(models, auth)) }));
  assert.equal((await request('/api/categorias', { method: 'POST', body: { nombre: 'Café' } })).status, 401);
  const category = await request('/api/categorias', { method: 'POST', token, body: { nombre: 'Café' } });
  assert.equal(category.status, 201);
  const cid = category.data.categoria._id;
  assert.equal((await request('/api/categorias', { method: 'POST', token, body: { nombre: 'café' } })).status, 409);
  assert.equal((await request('/api/productos', { method: 'POST', token, body: { nombre: 'Cortado', categoria: cid, precio: -1 } })).status, 400);
  assert.equal((await request('/api/productos', { method: 'POST', token, body: { nombre: 'Cortado', categoria: '000000000000000000000000' } })).status, 404);
  const product = await request('/api/productos', { method: 'POST', token, body: { nombre: 'Cortado', categoria: cid, precio: 1500, descripcion: 'Con leche' } });
  assert.equal(product.status, 201);
  const pid = product.data.producto._id;
  assert.equal((await request('/api/productos?limite=1')).data.total, 1);
  assert.equal((await request('/api/productos?desde=-1')).status, 400);
  assert.equal((await request('/api/buscar/productos/cor')).data.results.length, 1);
  assert.equal((await request('/api/buscar/productos/.*')).data.results.length, 0);
  assert.equal((await request(`/api/productos/${pid}`, { method: 'PUT', token, body: { precio: 1700 } })).data.producto.precio, 1700);
  assert.equal((await request(`/api/productos/${pid}`, { method: 'DELETE', token })).status, 403);
  assert.equal((await request(`/api/categorias/${cid}`, { method: 'DELETE', token: adminToken })).status, 409);
  assert.equal((await request(`/api/productos/${pid}`, { method: 'DELETE', token: adminToken })).status, 200);
  assert.equal((await request(`/api/buscar/productos/${pid}`)).data.results.length, 0);
  assert.equal((await request(`/api/productos/${pid}`)).status, 404);
  assert.equal((await request(`/api/categorias/${cid}`, { method: 'DELETE', token: adminToken })).status, 200);
});
